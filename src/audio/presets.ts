type Point = [hz: number, gain: number]

/**
 * Builds a smooth 18-band curve from log-frequency control points.
 * Linear interpolation in log-frequency space produces natural-looking
 * shelves without hand-tuning every band.
 */
export function shapeBands(points: Point[]): number[] {
  const sorted = [...points].sort((a, b) => a[0] - b[0])
  return EQ_FREQUENCIES.map((hz) => {
    if (hz <= sorted[0][0]) return round(sorted[0][1])
    if (hz >= sorted[sorted.length - 1][0]) return round(sorted[sorted.length - 1][1])
    for (let i = 0; i < sorted.length - 1; i++) {
      const [f0, g0] = sorted[i]
      const [f1, g1] = sorted[i + 1]
      if (hz >= f0 && hz <= f1) {
        const t = Math.log(hz / f0) / Math.log(f1 / f0)
        return round(g0 + (g1 - g0) * t)
      }
    }
    return 0
  })
}

function round(n: number): number {
  return Math.round(n * 10) / 10
}

